"""Positive control of the gate (ruling R30): the ``replay`` attack re-executes every target's real fraud episode
unchanged.

The candidate is ``REPLAY`` (``ReplayCandidate``); ``audit`` executes it on each target as the clean leg does – the
episode's real operations through the same bank, from the same pre-episode state – so VER_adv ≡ VER_clean per
target by construction, the paired uplift is exactly 0 and the gate's ``ver_uplift`` check must pass. A red gate
with this attack means the decision chain (uplift statistic, worst case, verdict) is broken, not the model.

No reconnaissance is spent (0 evaluations, 0 operations). The replayed operations are the observed data, not
operations generated by the attacker, so the threat-model feasibility check does not apply to them (``audit``
counts them as feasible and marks the targets ``replay``): about 2.7 % of the real test fraud operations lie outside
the realistic threat model (window, gap or coordinates), exactly as in the clean leg, which is never checked either.
It is never used for hardening (``harden.check_generation_attack`` accepts only ES and random search).
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from ..oracle import ReconOracle
from ..threat import ThreatModel
from .random_search import AttackRun


@dataclass(frozen=True)
class ReplayCandidate:
    """«Replay the target's real episode unchanged»: no parameters."""

    def as_dict(self) -> dict:
        return {"type": "replay"}


REPLAY = ReplayCandidate()


class ReplayAttack:
    """The positive control (module docstring)."""

    held_out = False
    positive_control = True

    def run(self, oracle: ReconOracle, tm: ThreatModel, rng: np.random.Generator) -> AttackRun:
        return AttackRun(best=REPLAY, best_fitness=float("nan"), evals=0, ops_used=0)
